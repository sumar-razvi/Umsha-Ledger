#!/usr/bin/env node
// Builds apps-script/Core.gs from /core/*.js so Apps Script runs exactly the
// code the Node tests cover.
//
// Each core file becomes one namespace in Core.gs, named after the file in
// PascalCase (money.js -> Money, posting.js -> Posting):
//
//   var Money = (function () { ...file body... return { ...exports }; })();
//
// Conventions core files must follow (the build fails otherwise):
//   - Import siblings only as   const Money = require('./money.js');
//     (the variable name must be the sibling's namespace name).
//   - End with exactly one      if (typeof module !== 'undefined') module.exports = { ... };
//
// Files are emitted in dependency order so every namespace exists before use.

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CORE_DIR = path.join(ROOT, 'core');
const OUT_FILE = path.join(ROOT, 'apps-script', 'Core.gs');
const SEED_DIR = path.join(ROOT, 'seed');
const SEED_FILE = path.join(ROOT, 'apps-script', 'Seed.gs');
// The same bundle for the browser (index.html), so the page parses and
// formats money with exactly the code the tests cover.
const BROWSER_FILE = path.join(ROOT, 'core.bundle.js');

const REQUIRE_RE = /^const (\w+) = require\('\.\/([\w-]+)\.js'\);[ \t]*\r?\n/gm;
const EXPORT_RE = /^if \(typeof module !== 'undefined'\) module\.exports = (\{[\s\S]*\});\s*$/m;

function namespaceFor(fileName) {
  return path.basename(fileName, '.js')
    .split(/[-_]/)
    .map(function (p) { return p.charAt(0).toUpperCase() + p.slice(1); })
    .join('');
}

function parseCoreFile(fileName, source) {
  const ns = namespaceFor(fileName);
  const deps = [];
  let body = source.replace(REQUIRE_RE, function (_, varName, dep) {
    const depNs = namespaceFor(dep + '.js');
    if (varName !== depNs) {
      throw new Error(fileName + ": require('./" + dep + ".js') must be assigned to `" + depNs + '`, not `' + varName + '`');
    }
    deps.push(dep + '.js');
    return '';
  });
  if (/\brequire\s*\(/.test(body)) {
    throw new Error(fileName + ': only top-level `const X = require(\'./x.js\');` imports of other core files are allowed');
  }
  const matches = body.match(new RegExp(EXPORT_RE.source, 'gm'));
  if (!matches || matches.length !== 1) {
    throw new Error(fileName + ": must end with exactly one `if (typeof module !== 'undefined') module.exports = {...};`");
  }
  body = body.replace(EXPORT_RE, function (_, obj) { return 'return ' + obj + ';\n'; });
  if (/module\.exports/.test(body)) {
    throw new Error(fileName + ': stray `module.exports` outside the final export statement');
  }
  return { fileName: fileName, ns: ns, deps: deps, body: body };
}

function sortByDependencies(files) {
  const byName = {};
  files.forEach(function (f) { byName[f.fileName] = f; });
  const ordered = [];
  const state = {}; // undefined | 'visiting' | 'done'
  function visit(f, trail) {
    if (state[f.fileName] === 'done') return;
    if (state[f.fileName] === 'visiting') {
      throw new Error('Circular require: ' + trail.concat(f.fileName).join(' -> '));
    }
    state[f.fileName] = 'visiting';
    f.deps.slice().sort().forEach(function (d) {
      if (!byName[d]) throw new Error(f.fileName + ' requires missing core file ' + d);
      visit(byName[d], trail.concat(f.fileName));
    });
    state[f.fileName] = 'done';
    ordered.push(f);
  }
  files.slice().sort(function (a, b) { return a.fileName < b.fileName ? -1 : 1; })
    .forEach(function (f) { visit(f, []); });
  return ordered;
}

function buildCore(coreDir) {
  const dir = coreDir || CORE_DIR;
  const files = fs.readdirSync(dir)
    .filter(function (n) { return n.endsWith('.js'); })
    .map(function (n) { return parseCoreFile(n, fs.readFileSync(path.join(dir, n), 'utf8')); });
  const ordered = sortByDependencies(files);

  const parts = [
    '// GENERATED by scripts/build-core.js from /core. Never edit by hand: change /core and run `npm run build`.',
    '// Namespaces: ' + ordered.map(function (f) { return f.ns; }).join(', '),
    '',
  ];
  ordered.forEach(function (f) {
    parts.push('// ---- core/' + f.fileName + ' ----');
    parts.push('var ' + f.ns + ' = (function () {');
    parts.push(f.body.replace(/\s+$/, ''));
    parts.push('})();');
    parts.push('');
  });
  const out = parts.join('\n');
  if (/module\.exports/.test(out) || /\brequire\s*\(/.test(out)) {
    throw new Error('Build output still contains module.exports or require()');
  }
  return out;
}

// Seed CSVs embedded for Setup.gs: var SEED = {chart_of_accounts: [...], ...}.
function buildSeed(seedDir) {
  const Csv = require('../core/csv.js');
  const dir = seedDir || SEED_DIR;
  const names = fs.readdirSync(dir).filter(function (n) { return n.endsWith('.csv'); }).sort();
  const parts = [
    '// GENERATED by scripts/build-core.js from /seed/*.csv. Never edit by hand: change /seed and run `npm run build`.',
    'var SEED = {',
  ];
  names.forEach(function (n) {
    const rows = Csv.parseObjects(fs.readFileSync(path.join(dir, n), 'utf8'));
    parts.push('  ' + JSON.stringify(path.basename(n, '.csv')) + ': [');
    rows.forEach(function (r) { parts.push('    ' + JSON.stringify(r) + ','); });
    parts.push('  ],');
  });
  parts.push('};', '');
  return parts.join('\n');
}

if (require.main === module) {
  try {
    const out = buildCore();
    fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
    fs.writeFileSync(OUT_FILE, out);
    fs.writeFileSync(BROWSER_FILE, out);
    console.log('Wrote ' + path.relative(ROOT, OUT_FILE) + ' and ' + path.relative(ROOT, BROWSER_FILE) + ' (' + out.split('\n').length + ' lines)');
    const seed = buildSeed();
    fs.writeFileSync(SEED_FILE, seed);
    console.log('Wrote ' + path.relative(ROOT, SEED_FILE) + ' (' + seed.split('\n').length + ' lines)');
  } catch (e) {
    console.error('build-core failed: ' + e.message);
    process.exit(1);
  }
}

module.exports = { buildCore, buildSeed, namespaceFor, OUT_FILE, SEED_FILE, BROWSER_FILE };
